//! The small JSON boundary read by the browser. HTML stays server-rendered.
use maud::{Markup, html};
use serde::{Deserialize, Serialize};
use ts_rs::TS;

/// A text form. Exact bytes and non-text copies use an ordinary product operation.
#[derive(Clone, Debug, Serialize, Deserialize, PartialEq, Eq, TS)]
#[serde(deny_unknown_fields)]
pub struct CopyForm {
    pub label: String,
    pub text: String,
}

#[derive(Clone, Debug, Serialize, Deserialize, PartialEq, Eq, TS)]
#[serde(deny_unknown_fields)]
pub struct CopyTarget {
    pub label: String,
    pub forms: Vec<CopyForm>,
}
impl CopyTarget {
    /// First form is the default. Values are escaped as an HTML attribute by maud.
    pub fn render(&self, content: Markup) -> Markup {
        html! {
            div data-copy=(serde_json::to_string(self).expect("copy strings serialize")) {
                (content)
                button type="button" data-copy-menu="" { "Copy" }
                span data-copy-feedback="" role="status" aria-live="polite" {}
            }
        }
    }
}

/// `target` is an element ID, not a selector. Ref URLs must be same-origin.
#[derive(Clone, Debug, Serialize, Deserialize, PartialEq, Eq, TS)]
#[serde(tag = "kind", rename_all = "snake_case", deny_unknown_fields)]
pub enum FragmentUpdate {
    Append { target: String, html: String },
    Replace { target: String, html: String },
    Ref { target: String, url: String },
}
impl FragmentUpdate {
    /// Reuse exactly the view function used for a full page.
    pub fn replace<A>(target: impl Into<String>, answer: &A, view: &impl crate::View<A>) -> Self {
        Self::Replace {
            target: target.into(),
            html: view.render(answer).into_string(),
        }
    }
    pub fn append<A>(target: impl Into<String>, answer: &A, view: &impl crate::View<A>) -> Self {
        Self::Append {
            target: target.into(),
            html: view.render(answer).into_string(),
        }
    }
    pub fn event(&self, position: &str) -> Result<String, String> {
        command_surface::SseEvent::json(position, "fragment", self)
            .and_then(|event| event.encode())
            .map_err(|error| error.to_string())
    }
}

#[derive(Clone, Debug, Serialize, Deserialize, PartialEq, Eq, TS)]
#[serde(deny_unknown_fields)]
pub struct Completion {
    pub value: String,
    pub label: String,
}

/// Current fragments and their shared read position are read atomically by the
/// product. Visibility refresh resumes the stream strictly after this snapshot.
#[derive(Clone, Debug, Serialize, Deserialize, PartialEq, Eq, TS)]
#[serde(deny_unknown_fields)]
pub struct Refresh {
    pub position: String,
    pub fragments: Vec<FragmentUpdate>,
}

/// Writes always submit the original operation request through its declared route.
/// `request` is opaque to the shell, generated by the product's operation table.
#[derive(Clone, Debug, Serialize, Deserialize, PartialEq, Eq, TS)]
#[serde(deny_unknown_fields)]
pub struct Action {
    pub operation: String,
    pub label: String,
    pub cli: String,
    pub key: Option<String>,
    pub route: String,
    pub write: bool,
    pub availability: ActionAvailability,
    pub request: String,
}
#[derive(Clone, Debug, Serialize, Deserialize, PartialEq, Eq, TS)]
#[serde(tag = "state", rename_all = "snake_case", deny_unknown_fields)]
pub enum ActionAvailability {
    Enabled,
    Disabled { reason: String },
    Partial { reason: String },
    Loading,
    Unavailable { reason: String },
}
impl Action {
    /// Build directly from the registered row and its request, including the CLI.
    pub fn from_table(
        table: &command_surface::OperationTable,
        availability: &command_surface::Availability,
        request: &command_surface::RunnableRequest,
        key: Option<String>,
    ) -> Result<Self, String> {
        let spec = table
            .descriptions()
            .into_iter()
            .find(|description| description.spec.name == request.operation)
            .ok_or("action is absent from the operation table")?
            .spec;
        let cli = table
            .cli_command(request)
            .map_err(|error| error.to_string())?;
        Self::from_operation(&spec, availability, request, cli, key)
    }
    pub fn from_operation(
        spec: &command_surface::OperationSpec,
        availability: &command_surface::Availability,
        request: &command_surface::RunnableRequest,
        cli: String,
        key: Option<String>,
    ) -> Result<Self, String> {
        if spec.name != request.operation {
            return Err("action request names a different operation".into());
        }
        if !spec.http_route.starts_with('/')
            || spec.http_route.starts_with("//")
            || spec.http_route.contains(['\r', '\n'])
        {
            return Err("operation route must be an origin-relative path".into());
        }
        if key.as_deref().is_some_and(|key| {
            crate::keys::KEYS
                .iter()
                .any(|binding| !binding.ctrl && binding.prefix.is_none() && binding.key == key)
        }) {
            return Err("product action cannot replace a shared key".into());
        }
        use command_surface::Availability as A;
        let availability = match availability {
            A::Enabled => ActionAvailability::Enabled,
            A::Disabled { reason } => ActionAvailability::Disabled {
                reason: reason.clone(),
            },
            A::Partial { reason } => ActionAvailability::Partial {
                reason: reason.clone(),
            },
            A::Loading => ActionAvailability::Loading,
            A::Unavailable { reason } => ActionAvailability::Unavailable {
                reason: reason.clone(),
            },
        };
        Ok(Self {
            operation: spec.name.clone(),
            label: spec.summary.clone(),
            cli,
            key,
            route: spec.http_route.clone(),
            write: spec.write,
            availability,
            request: serde_json::to_string(request).map_err(|error| error.to_string())?,
        })
    }
    pub fn render(&self) -> Markup {
        let disabled = !matches!(
            self.availability,
            ActionAvailability::Enabled | ActionAvailability::Partial { .. }
        );
        let reason = match &self.availability {
            ActionAvailability::Disabled { reason }
            | ActionAvailability::Partial { reason }
            | ActionAvailability::Unavailable { reason } => Some(reason.as_str()),
            ActionAvailability::Loading => Some("loading"),
            ActionAvailability::Enabled => None,
        };
        let action = serde_json::to_string(self).expect("action strings serialize");
        let label = html! { (self.label) @if let Some(reason) = reason { " (" (reason) ")" } };
        if self.write {
            html! {
                div data-action-item="" {
                    form method="post" action=(self.route) {
                        input type="hidden" name="request" value=(self.request);
                        button type="submit" data-action=(action) disabled[disabled] { (label) }
                        small { code { (self.cli) } @if let Some(key) = &self.key { " · " kbd { (key) } } }
                    }
                }
            }
        } else {
            let route = read_route(&self.route, &self.request);
            html! {
                div data-action-item="" {
                    @if disabled { button type="button" data-action=(action) disabled { (label) } }
                    @else { a href=(route) data-action=(action) { (label) } }
                    small { code { (self.cli) } @if let Some(key) = &self.key { " · " kbd { (key) } } }
                }
            }
        }
    }
}

/// This is produced from the Rust wire definitions, never maintained separately.
pub fn typescript() -> String {
    let declarations = [
        crate::keys::KeyAction::decl(),
        crate::keys::KeyBinding::decl(),
        CopyForm::decl(),
        CopyTarget::decl(),
        FragmentUpdate::decl(),
        Completion::decl(),
        Refresh::decl(),
        ActionAvailability::decl(),
        Action::decl(),
    ];
    format!(
        "// Generated by web-shell-types. Do not edit.\n{}\nexport const SHARED_KEYS: Array<KeyBinding> = {};\nexport const RELOAD_EVENT = {};\n",
        declarations
            .map(|decl| format!("export {decl}")
                .lines()
                .map(str::trim_end)
                .collect::<Vec<_>>()
                .join("\n"))
            .join("\n"),
        serde_json::to_string(crate::keys::KEYS).expect("key declarations serialize"),
        serde_json::to_string(command_surface::RELOAD_EVENT).expect("event name serializes")
    )
}

fn read_route(route: &str, request: &str) -> String {
    let mut route = route.to_owned();
    if let Ok(request) = serde_json::from_str::<command_surface::RunnableRequest>(request)
        && let Some(arguments) = request.arguments.as_object()
    {
        for (name, value) in arguments {
            if value.is_null() {
                continue;
            }
            let value = value
                .as_str()
                .map(str::to_owned)
                .unwrap_or_else(|| value.to_string());
            route.push(if route.contains('?') { '&' } else { '?' });
            route.push_str(&encode_component(name));
            route.push('=');
            route.push_str(&encode_component(&value));
        }
    }
    route
}
fn encode_component(value: &str) -> String {
    use std::fmt::Write;
    let mut encoded = String::new();
    for byte in value.bytes() {
        if byte.is_ascii_alphanumeric() || matches!(byte, b'-' | b'_' | b'.' | b'~') {
            encoded.push(char::from(byte));
        } else {
            write!(encoded, "%{byte:02X}").expect("string writes do not fail");
        }
    }
    encoded
}
